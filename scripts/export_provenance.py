#!/usr/bin/env python
"""Collect experiments/E###-*/provenance.yaml into one ARS `experiment_provenance[]` block.

    python scripts/export_provenance.py [--only E001,E003] [--out paper/passports/experiment_provenance.generated.yaml]

You supply the output to the ARS pipeline when it asks the experiment-intake question after Stage 1.
The script checks the required keys locally. For a full schema check, run ARS's own validator:
    python $ARS/scripts/check_experiment_provenance.py --passport <file>
"""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
REQUIRED = ("experiment_id", "title", "repro_lock", "planned_vs_executed", "negative_results", "known_limitations")


def check(entry: dict, path: Path) -> list[str]:
    errs = [f"{path}: missing key '{k}'" for k in REQUIRED if k not in entry]
    if entry.get("repro_lock") is None and not entry.get("repro_lock_reason"):
        errs.append(f"{path}: repro_lock is null but repro_lock_reason is empty")
    for i, u in enumerate(entry.get("planned_vs_executed") or []):
        if not u.get("executed") and not u.get("skip_reason"):
            errs.append(f"{path}: planned_vs_executed[{i}] executed:false needs skip_reason")
    if not entry.get("planned_vs_executed"):
        errs.append(f"{path}: planned_vs_executed must have at least one unit")
    return errs


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--only", default="", help="comma-separated experiment IDs")
    ap.add_argument("--out", default=str(ROOT / "paper/passports/experiment_provenance.generated.yaml"))
    args = ap.parse_args()
    only = {s.strip() for s in args.only.split(",") if s.strip()}

    entries, errs = [], []
    for p in sorted((ROOT / "experiments").glob("E[0-9][0-9][0-9]-*/provenance.yaml")):
        e = yaml.safe_load(p.read_text())
        if only and e.get("experiment_id") not in only:
            continue
        errs += check(e, p.relative_to(ROOT))
        entries.append(e)
    ids = [e.get("experiment_id") for e in entries]
    if len(ids) != len(set(ids)):
        errs.append(f"duplicate experiment_id among {ids}")
    if errs:
        sys.exit("provenance errors:\n  " + "\n  ".join(errs))

    out = Path(args.out)
    out.parent.mkdir(parents=True, exist_ok=True)
    out.write_text("# Generated by scripts/export_provenance.py. Do not edit; edit experiments/*/provenance.yaml.\n"
                   + yaml.safe_dump({"experiment_provenance": entries}, sort_keys=False, allow_unicode=True))
    print(f"wrote {len(entries)} entries → {out.relative_to(ROOT) if out.is_relative_to(ROOT) else out}")


if __name__ == "__main__":
    main()
